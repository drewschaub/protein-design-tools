def _parse(text: str):
    lines = [line.split() for line in text.splitlines() if line.strip()]
    assert lines[0] == list(ALPHABET)
    rows = []
    for line in lines[1:]:
        assert line[0] == ALPHABET[len(rows)]
        rows.append(tuple(int(x) for x in line[1:]))
    return tuple(rows)


#: ``BLOSUM62[i][j]`` scores ``ALPHABET[i]`` against ``ALPHABET[j]``.
BLOSUM62 = _parse(_TABLE)

#: Residue letter -> row/column index; unknown letters should map to ``"X"``.
